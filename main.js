  async syncChanges(changes) {
    if (this.busy)
      return;
    const actionable = changes.filter((c) => c.kind !== "unchanged");
    if (actionable.length === 0) {
      new import_obsidian6.Notice("Nothing to sync.");
      return;
    }
    this.busy = true;
    try {
      const result = await this.plugin.engine.applyChanges(
        actionable,
        (done, total, label) => {
          this.setStatus(`Syncing ${done}/${total}: ${label}`);
        }
      );
      let msg = `Synced ${result.ok} item(s).`;
      if (result.parsed > 0)
        msg += ` Parsing ${result.parsed}.`;
      if (result.failed > 0)
        msg += ` ${result.failed} failed.`;
      new import_obsidian6.Notice(msg);
      if (result.errors.length > 0) {
        console.error("RAGFlow Sync errors:", result.errors);
      }
    } catch (e) {
      new import_obsidian6.Notice(`Sync failed: ${e.message}`);
    } finally {
      this.busy = false;
      await this.scan();
    }
  }
  /**
   * Snooze the ticked files: snapshot each and add it to ignoredEntries so the
   * Scan diff shows it with an "Ignored" badge and "Sync all" skips it. It
   * re-surfaces on the next scan once its content drifts from the snapshot.
   */
  async ignoreSelected() {
    if (this.selected.size === 0) {
      new import_obsidian6.Notice("Tick the files you want to ignore.");
      return;
    }
    const picked = [...this.selected];
    for (const path of picked) {
      this.plugin.settings.ignoredEntries[path] = await this.plugin.engine.snapshotForIgnore(path);
    }
    await this.plugin.saveSettings();
    for (const change of this.changes) {
      if (this.selected.has(change.vaultPath))
        change.ignored = true;
    }
    this.selected.clear();
    this.render();
    new import_obsidian6.Notice(`Ignoring ${picked.length} file(s).`);
  }
