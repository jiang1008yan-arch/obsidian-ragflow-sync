var RagflowSyncPlugin = class extends import_obsidian7.Plugin {
  async onload() {
    await this.loadSettings();
    this.client = new RagflowClient(() => this.settings);
    this.store = new SyncStateStore(
      this.settings.state,
      () => this.saveSettings()
    );
    this.engine = new SyncEngine(
      this.app,
      this.client,
      this.store,
      () => this.settings
    );
    this.registerView(
      VIEW_TYPE_RAGFLOW_SYNC,
      (leaf) => new RagflowSyncView(leaf, this)
    );
    this.addRibbonIcon("refresh-cw", "RAGFlow Sync", () => {
      void this.activateView();
    });
    this.addCommand({
      id: "open-ragflow-sync-panel",
      name: "Open sync panel",
      callback: () => void this.activateView()
    });
    this.addCommand({
      id: "ragflow-scan-diff",
      name: "Scan for differences",
      callback: async () => {
        const view = await this.activateView();
        await view?.scan();
      }
    });
    this.addCommand({
      id: "ragflow-sync-all",
      name: "Sync all changes",
      callback: async () => {
        const view = await this.activateView();
        if (!view)
          return;
        await view.scan();
        await view.syncAll();
      }
    });
    this.addCommand({
      id: "ragflow-force-resync",
      name: "Force re-sync all (re-upload everything)",
      callback: async () => {
        const view = await this.activateView();
        if (!view)
          return;
        await view.scan();
        await view.forceSyncAll();
      }
    });
    this.addCommand({
      id: "ragflow-apply-tags",
      name: "Apply tags to chunks",
      callback: async () => {
        const view = await this.activateView();
        if (!view)
          return;
        await view.applyTagsAll();
      }
    });
    this.addSettingTab(new RagflowSyncSettingTab(this.app, this));
  }
  onunload() {
  }
  async activateView() {
    const { workspace } = this.app;
    let leaf = workspace.getLeavesOfType(VIEW_TYPE_RAGFLOW_SYNC)[0] ?? null;
    if (!leaf) {
      leaf = workspace.getRightLeaf(false);
      if (leaf) {
        await leaf.setViewState({
          type: VIEW_TYPE_RAGFLOW_SYNC,
          active: true
        });
      }
    }
    if (leaf) {
      workspace.revealLeaf(leaf);
      return leaf.view;
    }
    new import_obsidian7.Notice("Could not open RAGFlow Sync panel.");
    return null;
  }
  async loadSettings() {
    const data = await this.loadData() ?? {};
    this.settings = normalizeSettings(data);
  }
  async saveSettings() {
    await this.saveData(this.settings);
  }
};
