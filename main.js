var FENCE = /^\s*(```|~~~)/;
var DELIM_CELL = /^:?-+:?$/;
function splitRow(line) {
  const cells = [];
  let cur = "";
  let inCode = false;
  let bracketDepth = 0;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === "\\" && i + 1 < line.length) {
      const next = line[i + 1];
      cur += next === "|" ? "|" : "\\" + next;
      i++;
      continue;
    }
    if (ch === "`") {
      inCode = !inCode;
      cur += ch;
      continue;
    }
    if (!inCode && ch === "[" && line[i + 1] === "[") {
      bracketDepth++;
      cur += "[[";
      i++;
      continue;
    }
    if (!inCode && ch === "]" && line[i + 1] === "]" && bracketDepth > 0) {
      bracketDepth--;
      cur += "]]";
      i++;
      continue;
    }
    if (ch === "|" && !inCode && bracketDepth === 0) {
      cells.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  cells.push(cur);
  if (cells.length > 1 && cells[0].trim() === "")
    cells.shift();
  if (cells.length > 1 && cells[cells.length - 1].trim() === "")
    cells.pop();
  return cells.map((c) => c.trim());
}
function isDelimiterRow(cells) {
  return cells.length > 0 && cells.every((c) => DELIM_CELL.test(c));
}
function escapeCell(cell) {
  return cell.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();
}
function normalizeDelim(cell) {
  const left = cell.startsWith(":");
  const right = cell.endsWith(":");
  if (left && right)
    return ":---:";
  if (right)
    return "---:";
  if (left)
    return ":---";
  return "---";
}
function renderRow(cells, n) {
  const padded = cells.slice(0, n).map(escapeCell);
  while (padded.length < n)
    padded.push("");
  return `| ${padded.join(" | ")} |`;
}
function renderTable(header, delim, rows) {
  const n = header.length;
  const delimCells = delim.slice(0, n).map(normalizeDelim);
  while (delimCells.length < n)
    delimCells.push("---");
  return [
    renderRow(header, n),
    `| ${delimCells.join(" | ")} |`,
    ...rows.map((r) => renderRow(r, n))
  ].join("\n");
}
function normalizeTables(src) {
  const lines = src.split("\n");
  const out = [];
  let inFence = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (FENCE.test(line)) {
      inFence = !inFence;
      out.push(line);
      continue;
    }
    if (inFence) {
      out.push(line);
      continue;
    }
    const next = lines[i + 1];
    if (next !== void 0 && line.includes("|")) {
      const header = splitRow(line);
      const delim = splitRow(next);
      if (header.length >= 1 && header.length === delim.length && isDelimiterRow(delim)) {
        const rows = [];
        let j = i + 2;
        while (j < lines.length) {
          const l = lines[j];
          if (l.trim() === "" || FENCE.test(l) || !l.includes("|"))
            break;
          rows.push(splitRow(l));
          j++;
        }
        if (out.length > 0 && out[out.length - 1].trim() !== "")
          out.push("");
        out.push(renderTable(header, delim, rows));
        if (lines[j] !== void 0 && lines[j].trim() !== "")
          out.push("");
        i = j - 1;
        continue;
      }
    }
    out.push(line);
  }
  return out.join("\n");
}

