var IMAGE_EXT = /\.(png|jpe?g|gif|svg|webp|bmp)$/i;
function parseInner(inner) {
  const pipe = inner.indexOf("|");
  const linkPart = pipe >= 0 ? inner.slice(0, pipe) : inner;
  const alias = pipe >= 0 ? inner.slice(pipe + 1).trim() : void 0;
  const hash = linkPart.indexOf("#");
  const target = (hash >= 0 ? linkPart.slice(0, hash) : linkPart).trim();
  const heading = hash >= 0 ? linkPart.slice(hash + 1).trim() : void 0;
  return { target, heading, alias: alias || void 0 };
}
function noteTitle(target) {
  const last = target.split("/").pop() ?? target;
  return last.replace(/\.md$/i, "");
}
function linkDisplay(p) {
  if (p.alias)
    return p.alias;
  if (!p.target)
    return p.heading ?? "";
  const name = noteTitle(p.target);
  return p.heading ? `${name} > ${p.heading}` : name;
}
function internalizeWikilinks(content) {
  const withEmbeds = content.replace(
    /!\[\[([^[\]]+)\]\]/g,
    (_m, inner) => {
      const p = parseInner(inner);
      if (IMAGE_EXT.test(p.target)) {
        return `![${p.alias ?? noteTitle(p.target)}](${p.target})`;
      }
      return linkDisplay(p);
    }
  );
  return withEmbeds.replace(
    /\[\[([^[\]]+)\]\]/g,
    (_m, inner) => linkDisplay(parseInner(inner))
  );
}
function stripWikilinks(text) {
  return text.replace(
    /!?\[\[([^[\]]+)\]\]/g,
    (_m, inner) => linkDisplay(parseInner(inner))
  );
}
function dedupe(titles) {
  return [...new Set(titles.filter((t) => t.length > 0))];
}
function buildRelatedSection(related) {
  const outgoing = dedupe(related.outgoing);
  const incoming = dedupe(related.incoming);
  if (outgoing.length === 0 && incoming.length === 0)
    return "";
  const lines = ["## Related notes", ""];
  if (outgoing.length > 0)
    lines.push(`**Links:** ${outgoing.join(", ")}`, "");
  if (incoming.length > 0)
    lines.push(`**Backlinks:** ${incoming.join(", ")}`, "");
  return lines.join("\n").trimEnd();
}
function internalizeMarkdown(content, related) {
  const body = internalizeWikilinks(content);
  const section = buildRelatedSection(related);
  if (!section)
    return body;
  return `${body.replace(/\s+$/, "")}

${section}
`;
}

