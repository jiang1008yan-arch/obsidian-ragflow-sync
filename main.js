function changeSummary(leaves) {
  const counts = {
    new: 0,
    modified: 0,
    deleted: 0,
    unchanged: 0
  };
  let ignored = 0;
  for (const leaf of leaves) {
    if (!leaf.change)
      continue;
    if (leaf.change.ignored)
      ignored += 1;
    else
      counts[leaf.change.kind] += 1;
  }
  const parts = [];
  if (counts.new)
    parts.push(`${counts.new} new`);
  if (counts.modified)
    parts.push(`${counts.modified} modified`);
  if (counts.deleted)
    parts.push(`${counts.deleted} deleted`);
  if (ignored)
    parts.push(`${ignored} ignored`);
  return parts.join(", ");
}
